def render(m):
    v = M3[m.group(1)]
    f = m.group(2)
    if f == "hex":
        return "#" + x(v)
    if f == "hex_stripped":
        return x(v)
    return str(int(x(v)[{"red": 0, "green": 2, "blue": 4}[f]:][:2], 16))


