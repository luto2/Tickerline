def patch(path, fn):
    old = path.read_text() if path.exists() else ""
    new = fn(old)
    if new != old:
        write(path, new)


def square(qml):
    block = re.search(r"rounding: QtObject \{.*?\n    \}", qml, re.S)
    sq = re.sub(r"(property int \w+: )\d+", r"\g<1>0", block.group(0))
    return qml.replace(block.group(0), sq)


patch(II / "Appearance.qml", square)
patch(II / "Appearance.qml", lambda q: q.replace('"Material Symbols Rounded"', '"Material Symbols Sharp"'))
