STATE.mkdir(parents=True, exist_ok=True)

ap = argparse.ArgumentParser()
ap.add_argument("--matte", choices=["on", "off", "toggle"])
ap.add_argument("--night", choices=["on", "off"])
args = ap.parse_args()


def flag(name, change=None):
    f = STATE / name
    on = f.exists() and f.read_text().strip() == "on"
    if change:
        on = (not on) if change == "toggle" else change == "on"
        f.write_text("on" if on else "off")
    return on


MATTE, NIGHT = flag("matte", args.matte), flag("night", args.night)
VARIANT = "matte" if MATTE or NIGHT else "default"

